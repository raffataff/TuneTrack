"""Turn TuneTrack's built-in Faust synths and effects into C++ for the live engine.

Run from the repo root:  python engine/tools/gen_faust.py

The offline renderer compiles each device's DSP text at render time with its settings written in as constants
(tunetrack/synths.py). The live engine cannot compile Faust while it runs, so here every setting becomes a
control instead: one C++ class per synth template and per effect, with settings changed while the engine plays.
The DSP bodies are the ones in synths.py, untouched, so both engines compute the same sound.

Writes engine/gen/tt_faust_gen.h and copies the Faust architecture headers the engine needs (from the DawDreamer
package, the same Faust version that renders offline) into engine/third_party/faust/.
"""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from tunetrack import synths  # noqa: E402

GEN = ROOT / "engine" / "gen"
VENDOR = ROOT / "engine" / "third_party" / "faust"
ARCH_ROOTS = ["faust/dsp/poly-dsp.h", "faust/gui/MapUI.h", "faust/gui/meta.h", "faust/gui/UI.h", "faust/dsp/dsp.h"]


def _ctl(name: str, default: float) -> str:
    return f'{name} = hslider("{name}", {float(default)!r}, -1000000, 1000000, 0.000001);\n'


def synth_source(template: str) -> tuple[str, dict]:
    params: dict = {}
    for tpl, _desc, defaults in synths.SYNTHS.values():
        if tpl == template:
            for k, v in defaults.items():
                params.setdefault(k, v)
    ctl = "".join(_ctl(k, v) for k, v in params.items())
    return synths._HEAD.replace("vamp =", ctl + "vamp =", 1) + synths.TEMPLATES[template], params


def fx_source(name: str, sidechain: bool = False) -> tuple[str, dict]:
    _desc, defaults, body = synths.FX[name]
    if sidechain:
        body = synths.SIDECHAIN_BODIES[name]
    params = dict(defaults)
    if name == "delay":
        params["delay_sec"] = defaults["time"] * 60.0 / 120.0
    return 'import("stdfaust.lib");\n' + "".join(_ctl(k, v) for k, v in params.items()) + body, params


def vendor_headers(arch: Path) -> list[str]:
    todo, seen = list(ARCH_ROOTS), []
    while todo:
        rel = todo.pop()
        if rel in seen:
            continue
        src = arch / rel
        if not src.exists():
            continue
        seen.append(rel)
        dst = VENDOR / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
        todo += re.findall(r'#include\s+"(faust/[^"]+)"', src.read_text(encoding="utf-8", errors="replace"))
    return sorted(seen)


def main() -> None:
    import dawdreamer
    from dawdreamer.faust import FaustContext
    from dawdreamer.faust.box import boxFromDSP, boxToSource

    arch = Path(dawdreamer.__file__).parent / "architecture"
    if VENDOR.exists():
        shutil.rmtree(VENDOR)
    copied = vendor_headers(arch)

    jobs = [("synth", t, f"TtSynth_{t}", *synth_source(t)) for t in synths.TEMPLATES]
    jobs += [("fx", n, f"TtFx_{n}", *fx_source(n)) for n in synths.FX]
    jobs += [("fxsc", n, f"TtFxSc_{n}", *fx_source(n, True)) for n in synths.SIDECHAIN_BODIES]

    out = ["// Generated by engine/tools/gen_faust.py from tunetrack/synths.py. Do not edit; run the script again.",
           "// Include from exactly one .cpp file.", "#pragma once", "#include <string>",
           '#include "faust/dsp/dsp.h"', '#include "faust/gui/UI.h"', '#include "faust/gui/meta.h"', ""]
    for kind, name, cls, src, _params in jobs:
        with FaustContext():
            cpp = boxToSource(boxFromDSP(src), "cpp", cls)
        cpp = re.sub(r"#ifndef FAUSTCLASS\s*\n#define FAUSTCLASS \w+\n#endif\n", "", cpp)
        out += [f"// ---- {kind} {name} ----", cpp, ""]
        print(f"{kind:5} {name:12} {len(cpp):7} chars")
    out += ["inline ::dsp* ttCreateFaust(const std::string& kind, const std::string& name)", "{"]
    for kind, name, cls, _src, _params in jobs:
        out.append(f'    if (kind == "{kind}" && name == "{name}") return new {cls}();')
    out += ["    return nullptr;", "}", ""]
    GEN.mkdir(parents=True, exist_ok=True)
    (GEN / "tt_faust_gen.h").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {GEN / 'tt_faust_gen.h'}; vendored {len(copied)} Faust headers")


if __name__ == "__main__":
    main()
